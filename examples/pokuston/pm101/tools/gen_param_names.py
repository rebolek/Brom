#!/usr/bin/env python3
"""Generate param-names.rcl: the host-facing name and group of every PM-101 parameter.

Host shells want each name as a borrowed static c-string, and Brom folds
module+name into the slug a preset is keyed by, so the names are spelled out as
literals rather than assembled at run time. The layout here must match the
offsets in core.rcl; core-test.rcl checks the count.

    python3 examples/pokuston/pm101/tools/gen_param_names.py > examples/pokuston/pm101/param-names.rcl
"""

STAGES = 6
DCO_ENVS = ["Pitch", "DCW", "DPS", "Cutoff", "Resonance", "DCA"]
MIX_ENVS = ["Cutoff", "Resonance", "DCA"]
DCO_SCALARS = ["Wave A", "Wave B", "Window", "DCW", "DPS", "Filter", "Cutoff", "Resonance", "DCA"]
MIX_SCALARS = ["Mode", "Filter", "Cutoff", "Resonance", "DCA", "Shaper On", "Shaper", "Bit Depth", "Freq Divider"]
GLOBALS = ["Detune Octave", "Detune Note", "Detune Cent", "Vibrato Rate", "Vibrato Depth", "Osc Sync"]


def block(module, scalars, envs):
    rows = [(module, name) for name in scalars]
    for env in envs:
        for kind in ("Rate", "Level"):
            for stage in range(1, STAGES + 1):
                rows.append((module, f"{env} Env {kind} {stage}"))
    return rows


rows = block("DCO1", DCO_SCALARS, DCO_ENVS) + block("DCO2", DCO_SCALARS, DCO_ENVS)
rows += block("Mixer", MIX_SCALARS, MIX_ENVS)
rows += [("Global", name) for name in GLOBALS]
assert len(rows) == 213, len(rows)
assert len({(m, n) for m, n in rows}) == len(rows), "duplicate slug"

out = []
w = out.append
w('''Recoil [
    Title: "PM-101 host-facing parameter names"
    Description: {
        GENERATED by tools/gen_param_names.py -- edit the script, not this file.

        The module and name a parameter is declared with are what a host
        displays and also what brom/plugin/preset folds into the slug every
        factory preset is keyed by, so renaming one orphans it in every preset
        that mentions it.
    }
    Type: module
    Module: examples/pokuston/pm101/param-names
    Ffi: [c-string]
    Imports: []
    Exports: [pm101-param-name pm101-param-module]
]

pm101-param-name: func [
    "Return the host-facing name of a PM-101 parameter."
    #export
    id [u32!] "Public parameter id."
    return: [c-string!] "Borrowed static name, empty for an unknown id."
] [''')
for i, (m, n) in enumerate(rows):
    w(f'    if id = {i} [return as c-string! "{n}"]')
w('''    return as c-string! ""
]

pm101-param-module: func [
    "Return the host grouping of a PM-101 parameter."
    #export
    id [u32!] "Public parameter id."
    return: [c-string!] "Borrowed static group name."
] [''')
for lo, hi, m in ((0, 81, "DCO1"), (81, 162, "DCO2"), (162, 207, "Mixer"), (207, 213, "Global")):
    w(f'    if all [id >= {lo} id < {hi}] [return as c-string! "{m}"]')
w('''    return as c-string! ""
]''')
print("\n".join(out))
